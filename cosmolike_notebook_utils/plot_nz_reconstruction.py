"""Draw the manual histogram-reconstruction study from saved C-reader samples.

The same two-panel figure is regenerated by every project's explicit study
and its lightweight redraw command. It uses measured curves and cell areas;
no spline is refitted and no cosmology calculation is performed here.

A distribution is one source or lens tomographic bin. A histogram cell is
one redshift interval WITHIN that distribution. Keeping those two meanings
of "bin" separate is essential when choosing the close-up and labelling bars.

Run a project's tests/generate_nz_reconstruction_figures.py to call this
shared function with its saved JSON measurements and NPZ arrays. The
project's tests/studies/README.md explains the metric and how to recompute
the measurements; this module only draws them.
"""
from pathlib import Path
import json

import matplotlib.pyplot as plt
import numpy as np


def plot_nz_four_reconstructions(report_file, arrays_file, output_file):
    """Plot compiled original/3/5/7 curves and their redistribution of bin mass.

    The left panel zooms into one actual survey histogram edge. The right
    panel includes every source/lens distribution, so that selecting a single
    illustrative edge cannot hide larger area changes elsewhere. No plotted
    curve is refitted in Python.

    Arguments:
      report_file = JSON area audit: project label and one measurement row
                    per reconstruction and source/lens distribution.
      arrays_file = NPZ with original redshift edges, normalized cell masses,
                    and compiled density samples near the illustrated edge.
                    Redshift is dimensionless; n(z) is density per redshift.
      output_file = PNG path. Its parent directory must already exist.

    Array layout:
      edges[ncell+1] brackets target[ntomo, ncell], the input cell masses.
      target[tomo] / diff(edges) gives the selected histogram's densities.
      Each reconstruction has zoom_z[nquery] and zoom_density[nquery],
      sampled on the same close-up by the compiled-reader audit.
      ncell = redshift cells; ntomo = tomographic distributions; nquery =
      saved evaluation points. JSON bin labels count from one; arrays from zero.

    Returns:
      None. Saves and closes a two-panel figure; leaves matplotlib's global
      style and the recorded curves unchanged. Missing files/fields raise
      their ordinary Python exceptions instead of substituting new data.
    """
    report_path = Path(report_file)
    report_text = report_path.read_text()
    report = json.loads(report_text)
    rows = report["probability_audit"]["rows"]
    originals = []
    for row in rows:
        if row["arm"] == "original":
            originals.append(row)
    # 1. Choose one tomographic distribution using the ORIGINAL cubic's
    # all-cell redistribution score. This highlights where that interpretation
    # changes the supplied histogram most; it does not select whichever
    # Akima curve makes the largest contrast. An exact tie keeps the first
    # distribution in the audit's source/lens order.
    selected = originals[0]
    for row in originals[1:]:
        if row["bin_redistribution_pct"] > selected["bin_redistribution_pct"]:
            selected = row
    sample = selected["sample"]
    # The audit labels tomography from one for readers; NumPy indexes from zero.
    tomo = selected["tomographic_bin"] - 1

    # These parallel arrays describe the same four reconstructions in a fixed
    # order. Their shared index links each saved array name, legend and colour.
    arms = (
        "original",
        "three",
        "five",
        "seven",
    )
    labels = (
        "Original cubic",
        "3 points + Akima",
        "5 points + Akima",
        "7 points + Akima",
    )
    colours = (
        "#c45124",
        "#078b72",
        "#3567b5",
        "#a23d99",
    )
    fig, axes = plt.subplots(nrows=1, ncols=2, figsize=(14.2, 5.1))
    with np.load(file=arrays_file) as arrays:
        edges = arrays[sample + "_original_edges"]
        # 2. Locate the sharpest input transition within that distribution.
        # Cell probability divided by cell width is the histogram density,
        # so this comparison also has the right units for irregular cells.
        # diff(heights)[j] compares cells j and j+1; their shared edge has
        # index j+1. The added one therefore locates the EDGE, not a centre.
        # argmax keeps the first edge if two absolute jumps are equal.
        probabilities = arrays[sample + "_original_target"][tomo]
        widths = np.diff(edges)
        heights = probabilities / widths
        jumps = np.diff(heights)
        absolute_jumps = np.abs(jumps)
        cell = int(np.argmax(absolute_jumps)) + 1

        # 3. Keep enough neighbouring cells to see both plateaus and the
        # smoothing of their transitions: two before the chosen edge and
        # three after it. At an input boundary the window is shortened,
        # never extended beyond the supplied histogram. A last-centre
        # cutoff can therefore appear inside this window, rather than at
        # its right boundary. The project README gives a concrete example.
        left = max(0, cell - 2)
        right = min(heights.size, cell + 3)
        axes[0].stairs(values=heights, edges=edges, fill=True, color="0.6", alpha=.22,
                       label="Input histogram")
        axes[0].stairs(values=heights, edges=edges, color="0.45", linewidth=.8)
        # The audit sampled every C reader densely on this SAME window
        # (_sample_histogram_edge in cocoa_nz_testing.py). Draw those values
        # directly; another Python spline would alter the measured curves.
        plotted_values = [heights[left:right]]
        for curve_index in range(len(arms)):
            arm = arms[curve_index]
            label = labels[curve_index]
            colour = colours[curve_index]
            prefix = sample + "_" + arm
            z = arrays[prefix + "_zoom_z"]
            density = arrays[prefix + "_zoom_density"]
            # Matplotlib's plot requires x then y as positional arguments.
            axes[0].plot(z, density, color=colour, linewidth=2, label=label)
            plotted_values.append(density)
        # Include the histogram and all four curves when setting the
        # vertical range, with a small margin. Negative ringing and endpoint
        # drops remain visible rather than being clipped at density zero.
        values = np.concatenate(plotted_values)
        lower = float(np.min(values))
        upper = float(np.max(values))
        # Eight percent provides headroom; a floor based on one percent of
        # the histogram peak prevents a flat segment from collapsing the axis.
        density_range = upper - lower
        range_floor = .01 * np.max(heights)
        margin = .08 * max(density_range, range_floor)
        axes[0].set_ylim(bottom=lower - margin, top=upper + margin)
        axes[0].set_xlim(left=edges[left], right=edges[right])
    axes[0].set_title(f"Actual histogram edge · {sample} bin {tomo + 1}")
    axes[0].set_xlabel("Redshift z")
    axes[0].set_ylabel("Density n(z)")
    axes[0].legend(fontsize=8.5, loc="best")
    axes[0].grid(alpha=.15)

    # The right panel uses EVERY source/lens distribution, not just the
    # close-up's selected one. Each saved score is 50*sum(abs(q/sum(q)-p))
    # percent: p is normalized input cell mass, q is integrated reader area
    # in that same cell. Dividing by sum(q) isolates redistribution between
    # cells; total-area loss is a separate measurement in the README.
    bin_labels = []
    values_by_arm = {}
    for arm in arms:
        values_by_arm[arm] = []
    for original in originals:
        # S/L identifies source/lens; the number retains the audit's label.
        sample_initial = original["sample"][0].upper()
        bin_number = str(original["tomographic_bin"])
        bin_labels.append(sample_initial + bin_number)
        for arm in arms:
            for row in rows:
                if (row["sample"] == original["sample"]
                        and row["tomographic_bin"] == original["tomographic_bin"]
                        and row["arm"] == arm):
                    values_by_arm[arm].append(row["bin_redistribution_pct"])
    positions = np.arange(len(bin_labels))
    # Four adjacent bars of width 0.18 form a group centred on each label.
    # Offsets affect display only; heights remain the saved measurements.
    offsets = (
        -.27,
        -.09,
        .09,
        .27,
    )
    for curve_index in range(len(arms)):
        arm = arms[curve_index]
        label = labels[curve_index]
        colour = colours[curve_index]
        bar_positions = positions + offsets[curve_index]
        axes[1].bar(x=bar_positions, height=values_by_arm[arm], width=.18,
                    color=colour, label=label)
    axes[1].set_xticks(ticks=positions, labels=bin_labels, rotation=60, fontsize=8)
    axes[1].set_xlabel("Tomographic distribution: S = source, L = lens")
    axes[1].set_ylabel("Redistributed probability [%]")
    axes[1].set_title("Redistribution among original histogram cells")
    axes[1].legend(fontsize=8.5)
    axes[1].grid(axis="y", alpha=.15)
    fig.suptitle(report["project_label"] + " · four interpretations of the same n(z)",
                 fontsize=16)
    fig.tight_layout(rect=(0, 0, 1, .93))
    fig.savefig(fname=output_file, dpi=180)
    plt.close(fig)
