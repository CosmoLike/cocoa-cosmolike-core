"""Draw the manual histogram-reconstruction study from saved C-reader samples.

The same two-panel figure is regenerated by every project's explicit study
and its lightweight redraw command. It uses measured curves and cell areas;
no spline is refitted and no cosmology calculation is performed here.
"""
from pathlib import Path
import json

import matplotlib.pyplot as plt
import numpy as np


def plot_nz_four_reconstructions(report_file, arrays_file, output_file):
    """Plot compiled original/3/5/7 curves and their redistribution of bin mass.

    The left panel zooms into one actual survey histogram edge. The right
    panel includes every source/lens distribution, so that selecting a single
    illustrative edge cannot hide larger area changes elsewhere. No plotted
    curve is refitted in Python.

    Arguments:
      report_file = JSON area audit: project label and one measurement row
                    per reconstruction and source/lens distribution.
      arrays_file = NPZ with original redshift edges, normalized cell masses,
                    and compiled density samples near the illustrated edge.
                    Redshift is dimensionless; n(z) is density per redshift.
      output_file = PNG path. Its parent directory must already exist.

    Returns:
      None. Saves and closes a two-panel figure; leaves matplotlib's global
      style and the recorded curves unchanged. Missing files/fields raise
      their ordinary Python exceptions instead of substituting new data.
    """
    report = json.loads(Path(report_file).read_text())
    rows = report["probability_audit"]["rows"]
    originals = []
    for row in rows:
        if row["arm"] == "original":
            originals.append(row)
    # Use one reproducible edge for the overlay. The all-bin panel keeps
    # this illustrative choice from hiding larger changes in other bins.
    selected = originals[0]
    for row in originals[1:]:
        if row["bin_redistribution_pct"] > selected["bin_redistribution_pct"]:
            selected = row
    sample = selected["sample"]
    tomo = selected["tomographic_bin"] - 1
    arms = ("original", "three", "five", "seven")
    labels = ("Original cubic", "3 points + Akima", "5 points + Akima", "7 points + Akima")
    colours = ("#c45124", "#078b72", "#3567b5", "#a23d99")
    fig, axes = plt.subplots(nrows=1, ncols=2, figsize=(14.2, 5.1))
    with np.load(file=arrays_file) as arrays:
        edges = arrays[sample + "_original_edges"]
        heights = arrays[sample + "_original_target"][tomo] / np.diff(edges)
        cell = int(np.argmax(np.abs(np.diff(heights)))) + 1
        left = max(0, cell - 2)
        right = min(heights.size, cell + 3)
        axes[0].stairs(values=heights, edges=edges, fill=True, color="0.6", alpha=.22,
                       label="Input histogram")
        axes[0].stairs(values=heights, edges=edges, color="0.45", linewidth=.8)
        plotted_values = [heights[left:right]]
        for arm, label, colour in zip(arms, labels, colours):
            prefix = sample + "_" + arm
            z = arrays[prefix + "_zoom_z"]
            density = arrays[prefix + "_zoom_density"]
            axes[0].plot(z, density, color=colour, linewidth=2, label=label)
            plotted_values.append(density)
        values = np.concatenate(plotted_values)
        lower = float(np.min(values))
        upper = float(np.max(values))
        margin = .08 * max(upper - lower, .01 * np.max(heights))
        axes[0].set_ylim(bottom=lower - margin, top=upper + margin)
        axes[0].set_xlim(left=edges[left], right=edges[right])
    axes[0].set_title(f"Actual histogram edge · {sample} bin {tomo + 1}")
    axes[0].set_xlabel("Redshift z")
    axes[0].set_ylabel("Density n(z)")
    axes[0].legend(fontsize=8.5, loc="best")
    axes[0].grid(alpha=.15)

    bin_labels = []
    values_by_arm = {arm: [] for arm in arms}
    for original in originals:
        bin_labels.append(original["sample"][0].upper() + str(original["tomographic_bin"]))
        for arm in arms:
            for row in rows:
                if (row["sample"] == original["sample"]
                        and row["tomographic_bin"] == original["tomographic_bin"]
                        and row["arm"] == arm):
                    values_by_arm[arm].append(row["bin_redistribution_pct"])
    positions = np.arange(len(bin_labels))
    for offset, arm, label, colour in zip((-.27, -.09, .09, .27), arms, labels, colours):
        axes[1].bar(positions + offset, values_by_arm[arm], width=.18,
                    color=colour, label=label)
    axes[1].set_xticks(ticks=positions, labels=bin_labels, rotation=60, fontsize=8)
    axes[1].set_xlabel("Tomographic distribution: S = source, L = lens")
    axes[1].set_ylabel("Redistributed probability [%]")
    axes[1].set_title("Redistribution among original histogram cells")
    axes[1].legend(fontsize=8.5)
    axes[1].grid(axis="y", alpha=.15)
    fig.suptitle(report["project_label"] + " · four interpretations of the same n(z)",
                 fontsize=16)
    fig.tight_layout(rect=(0, 0, 1, .93))
    fig.savefig(fname=output_file, dpi=180)
    plt.close(fig)
