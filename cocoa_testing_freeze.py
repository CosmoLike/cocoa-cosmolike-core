"""The shared freeze generator behind each project's maintainer tool.

Every project's tests/generate_frozen_reference.py (re)creates the
frozen state its unit tests run on: the frozen configuration modules,
the generated data vectors with their dataset descriptors, the
reference chi2 values and the SHA-256 manifest. The machinery is the
same in every project, so it lives here; the project's thin script
keeps only its data (which vectors to generate, which mask variants
to retype, any extra steps) and calls freeze_main with them.

freeze_main keeps the command-line surface the projects always had
(--overwrite for the full freeze, --tatt-masks / --baryons and any
project extra flags for the incremental modes, and the internal
worker flags the tool spawns for itself), and it refuses to run
without a mode flag: regenerating redefines what the tests protect.

Every model-building step runs in a worker subprocess spawned on the
project's own script: the cosmolike C layer aborts a process that
initializes two configurations with different data-vector dimensions,
and one architecture serves every project.

This module must stay importable before cobaya loads (the thin
scripts set OMP_NUM_THREADS first), so cobaya is imported inside the
functions, never at the top.
"""

import json
import os
import shutil
import sys
import time

# The ISO form the frozen-module headers and _meta blocks carry.
STAMP_FORMAT = "%Y-%m-%dT%H:%M:%SZ"

# The one-line explanation stored inside the manifest file itself.
MANIFEST_COMMENT = ("SHA-256 of every file under tests/frozen/; "
                    "verified by every test before evaluating "
                    "anything.")

# The skeleton of one generated frozen-configuration module. The yaml
# goes inside r""" so latex backslashes in parameter labels survive.
# The backslash right after the opening quotes below swallows the
# first newline, and the {name} slots are filled by .format later.
MODULE_TEMPLATE = '''\
"""AUTO-GENERATED by generate_frozen_reference.py --overwrite ({stamp}).

Frozen, fully expanded cobaya configuration for {example}
(source: {source} resolved against the likelihood defaults of that day).
Do not edit by hand: the SHA-256 manifest pins this file, and any edit
makes every test fail. Regenerate deliberately instead.
"""

# The exact sampled-parameter point the reference chi2 was evaluated at
point = {point}

# Every option and every parameter written out explicitly: changing the
# live EXAMPLE_EVALUATE yaml files or the likelihood default yaml files
# does not affect this configuration
yaml_string = r"""
{yaml}
"""
'''


def frozen_data_relpath(u):
    """The ROOTDIR-relative path of the project's frozen data copy.

    Stored inside the frozen configurations as the likelihood data
    path. ROOTDIR-relative on purpose: the frozen modules stay
    portable across machines, and the tests overwrite it with the
    absolute path anyway.

    Arguments:
      u = the project's cocoa_test_utils module.

    Returns:
      "./projects/<project>/tests/frozen/data".
    """
    project = os.path.basename(os.path.dirname(u.TESTS_DIR))
    return f"./projects/{project}/tests/frozen/data"


def write_json(path, value):
    """Write one json file the way every frozen json is written.

    indent=2 pretty-prints; sort_keys fixes the key order so the file
    diffs cleanly; the extra write ends the file with a final newline.
    json stores the floats in their shortest exact form, so every
    value round-trips bit for bit.

    Arguments:
      path  = the file to write.
      value = the json-serializable value.

    Returns:
      nothing; the file is written.
    """
    with open(path, "w") as f:
        json.dump(value, f, indent=2, sort_keys=True)
        f.write("\n")


def write_manifest(u):
    """Hash every frozen file into the manifest and report the count.

    compute_manifest returns {relative path: sha256} for every file
    now under frozen/; the callers write it last, so it covers every
    file the earlier steps produced.

    Arguments:
      u = the project's cocoa_test_utils module.

    Returns:
      nothing; tests/manifest_sha256.json is written.
    """
    manifest = {
        "_comment": MANIFEST_COMMENT,
        "files": u.compute_manifest(),
    }
    write_json(u.MANIFEST_FILE, manifest)
    print(f"manifest: {len(manifest['files'])} files pinned")


def freeze_example(u, example, stamp):
    """Write one example's fully expanded frozen-configuration module.

    The expansion works by round trip through cobaya: build the model
    from the live example yaml (letting cobaya merge in the live
    likelihood defaults), then ask the model for its resolved
    configuration with model.info() and store that. The resolved form
    lists every option and every parameter explicitly, so the frozen
    module no longer depends on any live default.

    Arguments:
      u       = the project's cocoa_test_utils module.
      example = a key of u.EXAMPLES.
      stamp   = the UTC time string written into the module header.

    Returns:
      nothing; frozen/frozen_config_<example>.py is written.

    Raises:
      ValueError when a sampled parameter is neither overridden by the
      example's evaluate block nor given a ref center to fall back on
      (the point would be undefined at that parameter).
    """
    from cobaya.yaml import yaml_load_file, yaml_dump

    project_dir = os.path.dirname(u.TESTS_DIR)
    data_relpath = frozen_data_relpath(u)
    cfg = u.EXAMPLES[example]
    live = yaml_load_file(os.path.join(project_dir, cfg["provenance"]))
    # The evaluate sampler's override block is the example's fiducial
    # point; keep it before stripping the sampler from the info.
    # dict(...) makes an independent copy, so the pop below cannot
    # take the block with it.
    override = dict(live["sampler"]["evaluate"]["override"])
    live.pop("sampler", None)
    live.pop("output", None)
    live["debug"] = 30
    live["timing"] = False
    # a reduced configuration reuses its source example's yaml with
    # the likelihood renamed (for example combo_3x2pt -> combo_2x2pt:
    # same options, same data, different probe selection inside
    # cosmolike). .get falls back to the plain likelihood name for
    # the entries that carry no source_likelihood key
    source_name = cfg.get("source_likelihood", cfg["likelihood"])
    # pop removes the block from the dictionary and hands it back, so
    # the next line can re-insert it under the target name
    likelihood_block = live["likelihood"].pop(source_name)
    live["likelihood"][cfg["likelihood"]] = likelihood_block
    likelihood_block["path"] = data_relpath
    # the frozen configuration stores NLA (IA_model 0);
    # load_frozen_info switches a copy to TATT (IA_model 1) for the
    # TATT variants
    likelihood_block["IA_model"] = 0
    if cfg.get("emulator"):
        # the emulated BAO/SN network (emulbaosn) runs on the device
        # its example names; setting "cpu" here keeps the reference
        # reproducible on machines without a CUDA GPU whatever the
        # example says (and torch on cpu is deterministic)
        live["theory"]["emulbaosn"]["extra_args"]["device"] = "cpu"

    # make_model builds the evaluable cobaya Model; building it is
    # what forces cobaya to merge the live likelihood defaults into
    # the configuration
    model = u.make_model(live)
    # model.info() returns the configuration with every default
    # resolved: the complete likelihood option set and the complete
    # parameter list, exactly what must be frozen.
    updated = model.info()
    updated.pop("output", None)
    updated.pop("packages_path", None)
    updated["likelihood"][cfg["likelihood"]]["path"] = data_relpath

    # The frozen point: the example's override where given, the ref
    # center otherwise. Fallbacks are printed so the maintainer can
    # confirm each one is intended.
    point = {}
    fallback = []
    for name in model.parameterization.sampled_params():
        if name in override:
            point[name] = override[name]
        else:
            # ref is either a {dist, loc, scale} block or a bare
            # number; the a-if-else picks the center in the first
            # case and the number itself in the second
            ref = updated["params"][name].get("ref")
            point[name] = ref["loc"] if isinstance(ref, dict) else ref
            fallback.append(name)
            if point[name] is None:
                raise ValueError(
                    f"parameter {name}: not in override and no ref")
    if fallback:
        print(f"{example}: point uses ref centers for {fallback}",
              flush=True)

    # the with block closes the file once the write finishes, even
    # on error. .format fills the template's {name} slots; json.dumps
    # renders the point as literal text (json syntax is valid python
    # here), sort_keys fixing the order; rstrip("\n") trims trailing
    # newlines so the template's closing quotes sit flush
    with open(os.path.join(u.FROZEN_DIR, cfg["frozen_module"]),
              "w") as f:
        f.write(MODULE_TEMPLATE.format(
            stamp=stamp,
            example=example,
            source=cfg["provenance"],
            point=json.dumps(point, indent=4, sort_keys=True),
            yaml=yaml_dump(updated).rstrip("\n"),
        ))
    print(f"{example}: frozen config expanded to "
          f"{len(updated['params'])} parameters "
          f"({len(live['params'])} in the live example yaml)",
          flush=True)


def _count_lines(path):
    """Count the lines of one file without loading it into memory.

    sum(1 for _ in f) walks the file line by line and adds 1 per line
    (_ is the customary name for an unused value): a streaming count,
    so a large data vector never sits in memory at once.

    Arguments:
      path = the file to count.

    Returns:
      the number of lines.
    """
    with open(path) as f:
        return sum(1 for _ in f)


def _retype_descriptor_line(descriptor, key, value, source):
    """Replace exactly one `key = ...` line of a dataset descriptor.

    keepends=True keeps each line's newline character, so the
    rewritten descriptor reproduces the original line endings and
    only the retyped line differs.

    Arguments:
      descriptor = the descriptor text to rewrite.
      key        = the descriptor key whose line is retyped (e.g.
                   "data_file" or "mask_file").
      value      = the file name written after the key.
      source     = the descriptor's name, for the error message.

    Returns:
      the rewritten descriptor text.

    Raises:
      RuntimeError unless exactly one line starts with the key.
    """
    replaced = 0
    out_lines = []
    for line in descriptor.splitlines(keepends=True):
        if line.strip().startswith(key):
            out_lines.append(f"{key} = {value}\n")
            replaced += 1
        else:
            out_lines.append(line)
    if replaced != 1:
        raise RuntimeError(
            f"{source}: expected exactly one {key} line, "
            f"found {replaced}")
    # "".join glues the kept lines back into one text; nothing is
    # inserted between them (each line kept its newline)
    return "".join(out_lines)


def _write_generated_vector(u, example, dataset_name, tatt, baryon,
                            point_overrides, what):
    """Generate one data vector and write its dataset descriptor.

    The vector is the example's theory prediction at the frozen point
    (with the requested IA variant, and with the bfmt theory block
    computing one feedback method for the baryon vectors), printed by
    the likelihood during one evaluation. It must be generated
    against the original frozen dataset (the descriptor written here
    does not exist yet; the printed theory vector does not depend on
    which data vector it is compared against). Runs inside a worker
    subprocess: it builds a model, and two different-dimension builds
    in one process abort (see cocoa_testing).

    Arguments:
      u               = the project's cocoa_test_utils module.
      example         = the generating example (a key of u.EXAMPLES).
      dataset_name    = the descriptor file name to write.
      tatt            = True evaluates the TATT variant.
      baryon          = a u.BARYON_METHODS label, or None.
      point_overrides = parameter values merged over the frozen
                        point, or None.
      what            = one word naming the vector kind in messages.

    Returns:
      nothing; frozen/data/ gains the .modelvector and .dataset
      files.

    Raises:
      RuntimeError when the generated vector's length differs from
      the original data vector (a masking or probe mismatch), or when
      the dataset descriptor does not contain exactly one data_file
      line to replace.
    """
    from cobaya.yaml import yaml_load

    cfg = u.EXAMPLES[example]
    # the original dataset name comes from the frozen configuration
    # itself (load_frozen_info would already point at the generated
    # dataset)
    frozen_info = yaml_load(u._frozen_module(example).yaml_string)
    original_dataset = (
        frozen_info["likelihood"][cfg["likelihood"]]["data_file"])

    vector_name = dataset_name.replace(".dataset", ".modelvector")
    if baryon is None:
        info = u.load_frozen_info(example, tatt=tatt)
    else:
        info = u.load_frozen_info(example, tatt=tatt, baryon=baryon)
    likelihood_block = info["likelihood"][cfg["likelihood"]]
    likelihood_block["data_file"] = original_dataset
    likelihood_block["print_datavector"] = True
    likelihood_block["print_datavector_file"] = (
        frozen_data_relpath(u) + "/" + vector_name)

    label = f"{example}, {'TATT' if tatt else 'NLA'} point"
    if baryon is not None:
        label = baryon
    print(f"generating {vector_name} ({label}) ...", flush=True)
    model = u.make_model(info)
    point = dict(u.build_point(model, example, tatt=tatt))
    if point_overrides:
        point.update(point_overrides)
    u.evaluate_chi2(model, point)

    # sanity: the generated vector must have the same length as the
    # original one, or the masks would select the wrong entries
    data_dir = os.path.join(u.FROZEN_DIR, "data")
    generated_lines = _count_lines(os.path.join(data_dir, vector_name))
    with open(os.path.join(data_dir, original_dataset)) as f:
        descriptor = f.read()
    original_vector = None
    # splitlines() cuts the text into a list of lines, newlines
    # removed; strip() trims surrounding whitespace before the match
    for line in descriptor.splitlines():
        if line.strip().startswith("data_file"):
            # split("=", 1) cuts at the first "=" only; [1] is the
            # part after it, stripped of spaces: the file name
            original_vector = line.split("=", 1)[1].strip()
    original_lines = _count_lines(os.path.join(data_dir,
                                               original_vector))
    if generated_lines != original_lines:
        raise RuntimeError(
            f"generated {what} vector has {generated_lines} lines; "
            f"the original {original_vector} has {original_lines}")

    # the generated dataset descriptor: the original with only the
    # data_file line replaced
    rewritten = _retype_descriptor_line(
        descriptor, "data_file", vector_name, original_dataset)
    with open(os.path.join(data_dir, dataset_name), "w") as f:
        f.write(rewritten)
    print(f"{what} vector: {vector_name} ({generated_lines} lines); "
          f"descriptor: {dataset_name}", flush=True)


def generate_datavector(u, dataset_name, vectors):
    """Write one generated data vector named by the vectors roster.

    Arguments:
      u            = the project's cocoa_test_utils module.
      dataset_name = a key of the roster, which is also the file name
                     of the descriptor to write.
      vectors      = the project's roster {dataset: (example, tatt)}.

    Returns:
      nothing; see _write_generated_vector.
    """
    example, tatt = vectors[dataset_name]
    _write_generated_vector(u, example, dataset_name, tatt=tatt,
                            baryon=None, point_overrides=None,
                            what="TATT" if tatt else "data")


def generate_baryon_datavector(u, label):
    """Write one feedback method's frozen data vector and descriptor.

    The vector is the example1 theory prediction with the bfmt theory
    block computing this method's suppression, at the frozen fiducial
    point plus the method's cosmology override
    (u.BARYON_POINT_OVERRIDES, e.g. BACCOemu's omegab shift into its
    training box). The drift tests evaluate against this vector: at
    freeze time the chi2 is zero by construction, so any later chi2
    above the tolerance means cosmolike or the theory block changed
    its prediction. (The accuracy checks regenerate their vector on
    the fly per run and do not use these files.)

    Arguments:
      u     = the project's cocoa_test_utils module.
      label = a u.BARYON_METHODS label.

    Returns:
      nothing; see _write_generated_vector.
    """
    _write_generated_vector(
        u, "example1", u._baryon_dataset(label), tatt=False,
        baryon=label,
        point_overrides=u.BARYON_POINT_OVERRIDES.get(label, {}),
        what="baryon")


def generate_tatt_mask_datasets(u, variants):
    """Write the per-mask TATT dataset descriptors.

    Each variant is a base descriptor with only its mask_file line
    retyped: the comparison sweeps read them through the --mask
    option to evaluate the same generated vector under another
    scale-cut mask. Pure text, no model evaluations, so the variants
    regenerate in the --overwrite run and in the incremental
    --tatt-masks mode alike.

    Arguments:
      u        = the project's cocoa_test_utils module.
      variants = the project's table {variant: (base, mask file)}.

    Returns:
      nothing; frozen/data/ gains one descriptor per variant.

    Raises:
      RuntimeError when a base descriptor does not contain exactly
      one mask_file line.
    """
    data_dir = os.path.join(u.FROZEN_DIR, "data")
    for variant, (base, mask) in variants.items():
        with open(os.path.join(data_dir, base)) as f:
            descriptor = f.read()
        rewritten = _retype_descriptor_line(descriptor, "mask_file",
                                            mask, base)
        with open(os.path.join(data_dir, variant), "w") as f:
            f.write(rewritten)
        print(f"TATT mask variant: {variant} (mask_file = {mask})",
              flush=True)


def reference_variants(cfg):
    """The reference variants one EXAMPLES entry earns.

    Every configuration gets an NLA reference. TATT only makes sense
    for the exact-physics configurations that carry a TATT dataset
    (the emulator entries are advisory and compared at their shipped
    IA settings; the cluster combinations have no TATT at all). The
    FASTPT variant exists where the tests need its baseline.

    Arguments:
      cfg = one entry of the project's EXAMPLES table.

    Returns:
      a list of (suffix, keyword table) pairs for single_model_chi2.
    """
    variants = [("nla", {"tatt": False})]
    if "tatt_dataset" in cfg and not cfg.get("emulator"):
        variants.append(("tatt", {"tatt": True}))
    if cfg.get("fastpt_reference"):
        variants.append(("tatt_fastpt", {"tatt": True, "fastpt": True}))
    return variants


def compute_references(u, stamp, chi2_format):
    """Evaluate and write the frozen reference chi2 values.

    Each value comes from single_model_chi2, exactly the way the
    tests will compute it. Where a configuration carries a FASTPT
    reference, the FASTPT-minus-CFASTPT difference is stored too:
    how much the two implementations of the TATT perturbation-theory
    terms differ at the reference point (the FASTPT tests print it).

    Arguments:
      u           = the project's cocoa_test_utils module.
      stamp       = the UTC time string for the _meta block.
      chi2_format = the print format of the chi2 values (".6f", or
                    ".6e" where the references sit near zero and
                    fixed decimals would print 0.000000).

    Returns:
      nothing; frozen/reference_chi2.json is written.
    """
    reference = {
        "_meta": {
            "generated_utc": stamp,
            "omp_num_threads": os.environ["OMP_NUM_THREADS"],
            "chi2_tolerance": u.CHI2_TOLERANCE,
        }
    }
    # .items() hands out (name, configuration) pairs, unpacked into
    # the two loop names
    for example, cfg in u.EXAMPLES.items():
        # each variant is a (suffix, keyword table) pair
        for suffix, kwargs in reference_variants(cfg):
            key = f"{example}_{suffix}"
            t0 = time.time()
            # **kwargs spreads the table into keyword arguments:
            # tatt=..., and fastpt=... where present
            chi2 = u.single_model_chi2(example, **kwargs)
            # :.1f prints the elapsed seconds with one decimal
            print(f"{key}: chi2 = {chi2:{chi2_format}}  "
                  f"({time.time() - t0:.1f}s)", flush=True)
            reference[key] = chi2
    for example, cfg in u.EXAMPLES.items():
        if cfg.get("fastpt_reference"):
            reference[f"{example}_fastpt_minus_cfastpt"] = (
                reference[f"{example}_tatt_fastpt"]
                - reference[f"{example}_tatt"])

    write_json(u.REFERENCE_FILE, reference)


def _run_worker(script_file, args, what):
    """Spawn one worker subprocess on the project's own script.

    subprocess.run starts the child (sys.executable = this same
    python) and BLOCKS until it exits; the child re-runs the
    project's thin script, whose __main__ block hands the worker flag
    back to freeze_main.

    Arguments:
      script_file = the project's generate_frozen_reference.py path.
      args        = the command-line arguments after the script.
      what        = a short name for the error message.

    Returns:
      nothing.

    Raises:
      RuntimeError when the worker exits nonzero.
    """
    import subprocess

    completed = subprocess.run([sys.executable, script_file]
                               + list(args))
    if completed.returncode != 0:
        raise RuntimeError(f"{what} failed")


def freeze_main(u, script_file, usage, vectors, mask_variants=None,
                data_ignore=(".DS_Store",), baryons=True,
                extra_steps=(), chi2_format=".6f"):
    """Run the mode the command-line flags select; return the exit code.

    The flags are checked in this order, and the first one present
    wins:
      --freeze-one X --stamp T, --vector-one D, --baryon-one L, and
      any extra step's worker flag
          worker modes: one model-building step each, then exit;
      --tatt-masks
          rewrite the per-mask TATT descriptors and re-pin the
          manifest (projects with mask_variants);
      --baryons
          add the per-method frozen baryon vectors and re-pin the
          manifest (projects with the baryonic-feedback suites);
      any extra step's incremental flag
          run that step alone and re-pin the manifest;
      --overwrite
          the full freeze: recreate frozen/, copy the data and the
          example snapshots, write the expanded configuration
          modules, the generated data vectors and mask descriptors,
          run the extra steps, evaluate the reference chi2 values,
          and hash everything into the manifest last, so it covers
          every file written before.
    Without any of them it prints the project's usage text and
    refuses.

    The incremental modes verify the existing frozen state against
    the manifest before touching it, so a hand-edited frozen file is
    refused instead of silently re-pinned.

    Arguments:
      u             = the project's cocoa_test_utils module.
      script_file   = the thin script's own path (__file__ there);
                      the workers re-run it.
      usage         = the thin script's docstring, printed on
                      refusal.
      vectors       = {dataset: (example, tatt)}: the data vectors
                      --overwrite regenerates.
      mask_variants = {variant: (base, mask file)} for the per-mask
                      descriptors, or None for a project without
                      them.
      data_ignore   = copytree ignore patterns for the frozen data
                      copy.
      baryons       = whether the project carries the
                      baryonic-feedback suites (and so the --baryons
                      mode and the baryon vectors).
      extra_steps   = (incremental_flag, worker_flag, needs_stamp,
                      run) tuples for project-specific stages, run in
                      --overwrite after the mask descriptors and
                      before the references; run takes the stamp when
                      needs_stamp, nothing otherwise.
      chi2_format   = the reference chi2 print format (see
                      compute_references).

    Returns:
      0 on success, 1 on refusal.
    """
    script_file = os.path.abspath(script_file)

    # worker modes first: each runs a single model-building step in
    # the process the parent spawned for it and exits
    if "--freeze-one" in sys.argv:
        u.require_cocoa_environment()
        # sys.argv.index finds the flag's position in the argument
        # list; the entry after it (+ 1) is the flag's value
        example = sys.argv[sys.argv.index("--freeze-one") + 1]
        stamp = sys.argv[sys.argv.index("--stamp") + 1]
        freeze_example(u, example, stamp)
        return 0
    if "--vector-one" in sys.argv:
        u.require_cocoa_environment()
        dataset_name = sys.argv[sys.argv.index("--vector-one") + 1]
        generate_datavector(u, dataset_name, vectors)
        return 0
    if baryons and "--baryon-one" in sys.argv:
        u.require_cocoa_environment()
        label = sys.argv[sys.argv.index("--baryon-one") + 1]
        generate_baryon_datavector(u, label)
        return 0
    for incremental_flag, worker_flag, needs_stamp, run in extra_steps:
        if worker_flag in sys.argv:
            u.require_cocoa_environment()
            if needs_stamp:
                run(sys.argv[sys.argv.index("--stamp") + 1])
            else:
                run()
            return 0

    if mask_variants is not None and "--tatt-masks" in sys.argv:
        # incremental: rewrite the per-mask descriptors of the --mask
        # comparison sweeps in an existing frozen state and re-pin
        # the manifest; pure text, no model evaluations
        u.require_cocoa_environment()
        u.verify_frozen()
        generate_tatt_mask_datasets(u, mask_variants)
        write_manifest(u)
        return 0
    if baryons and "--baryons" in sys.argv:
        # incremental: add the per-method frozen baryon vectors of
        # the drift tests to an existing frozen state and re-pin the
        # manifest; nothing else changes
        u.require_cocoa_environment()
        u.verify_frozen()
        for label, _, _ in u.BARYON_METHODS:
            _run_worker(script_file, ["--baryon-one", label],
                        f"baryon worker for {label!r}")
        write_manifest(u)
        return 0
    for incremental_flag, worker_flag, needs_stamp, run in extra_steps:
        if incremental_flag in sys.argv:
            # incremental: run this one project step in an existing
            # frozen state and re-pin the manifest
            u.require_cocoa_environment()
            u.verify_frozen()
            args = [worker_flag]
            if needs_stamp:
                stamp = time.strftime(STAMP_FORMAT, time.gmtime())
                args += ["--stamp", stamp]
            _run_worker(script_file, args,
                        f"{incremental_flag} worker")
            write_manifest(u)
            return 0

    if "--overwrite" not in sys.argv:
        print(usage)
        print("Refusing to run without --overwrite (this redefines "
              "the frozen state every test compares against).")
        return 1
    u.require_cocoa_environment()
    # time.gmtime() is the current time in UTC; strftime prints it
    # in the ISO form the frozen-module headers carry
    stamp = time.strftime(STAMP_FORMAT, time.gmtime())

    if os.path.isdir(u.FROZEN_DIR):
        shutil.rmtree(u.FROZEN_DIR)
    os.makedirs(u.FROZEN_DIR)

    project_dir = os.path.dirname(u.TESTS_DIR)
    print("freezing ../data ...", flush=True)
    # the data copy is what lets users change ../data later without
    # touching the tests; .DS_Store (macOS Finder metadata) would
    # only pollute the manifest. ignore_patterns builds the filter
    # function copytree consults in every folder it copies
    shutil.copytree(os.path.join(project_dir, "data"),
                    os.path.join(u.FROZEN_DIR, "data"),
                    ignore=shutil.ignore_patterns(*data_ignore))
    # .values() iterates the entry dictionaries; the keys are not
    # needed for the snapshot copies (examples sharing a provenance
    # yaml copy it more than once, to the same destination)
    for cfg in u.EXAMPLES.values():
        shutil.copy2(os.path.join(project_dir, cfg["provenance"]),
                     os.path.join(u.FROZEN_DIR, cfg["provenance"]))

    # one worker subprocess per model-building step; iterating a
    # dictionary yields its keys
    for example in u.EXAMPLES:
        _run_worker(script_file,
                    ["--freeze-one", example, "--stamp", stamp],
                    f"freeze worker for {example}")
    # the generated data vectors must exist before the reference
    # loop below: the TATT references evaluate against them
    for dataset_name in vectors:
        _run_worker(script_file, ["--vector-one", dataset_name],
                    f"vector worker for {dataset_name}")

    if mask_variants is not None:
        generate_tatt_mask_datasets(u, mask_variants)

    for incremental_flag, worker_flag, needs_stamp, run in extra_steps:
        args = [worker_flag]
        if needs_stamp:
            args += ["--stamp", stamp]
        _run_worker(script_file, args, f"{incremental_flag} worker")

    compute_references(u, stamp, chi2_format)
    write_manifest(u)
    return 0
